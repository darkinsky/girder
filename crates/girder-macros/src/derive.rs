//! Expansion of `#[derive(Typert)]`.
//!
//! The output builds a `Schema::Object` at runtime from the field list. Nothing is evaluated at
//! compile time beyond reading the tokens: the schema is a value, so a caller can render it at any
//! revision, and a test can compare it against the hand-written version.

use proc_macro::TokenStream;
use proc_macro2::TokenStream as TokenStream2;
use quote::quote;
use syn::{Data, DeriveInput, Fields, LitInt, LitStr, parse_macro_input};

use crate::schema_path::schema_crate;

/// Attributes this derive understands on a container or a field.
#[derive(Default)]
struct TypertAttrs {
    name: Option<String>,
    rename: Option<String>,
    added_in: Option<u32>,
    optional: bool,
}

/// Expands the derive.
pub fn expand(input: TokenStream) -> TokenStream {
    let input = parse_macro_input!(input as DeriveInput);
    match expand_inner(&input) {
        Ok(tokens) => tokens.into(),
        Err(error) => error.to_compile_error().into(),
    }
}

fn expand_inner(input: &DeriveInput) -> syn::Result<TokenStream2> {
    let schema_crate = schema_crate();
    let container = parse_attrs(&input.attrs)?;
    let struct_name = &input.ident;
    let schema_name = container
        .name
        .clone()
        .unwrap_or_else(|| struct_name.to_string());

    let Data::Struct(data) = &input.data else {
        // An enum is a discriminated union, which needs its own expansion rather than a variant of
        // this one. Handled by `expand_enum` so neither path grows a branch the other cannot reach.
        if let Data::Enum(data) = &input.data {
            return expand_enum(input, data, &container, &schema_crate);
        }
        return Err(syn::Error::new_spanned(
            struct_name,
            "Typert can be derived only for structs and enums with named or unit fields",
        ));
    };

    let Fields::Named(fields) = &data.fields else {
        return Err(syn::Error::new_spanned(
            struct_name,
            "Typert needs named fields; a tuple struct has no field names to put on the wire",
        ));
    };

    let mut field_tokens = Vec::new();
    for field in &fields.named {
        let attrs = parse_attrs(&field.attrs)?;
        let ident = field.ident.as_ref().expect("named fields have identifiers");
        let wire_name = attrs.rename.clone().unwrap_or_else(|| ident.to_string());

        let ty = &field.ty;
        let base = schema_for_type(ty, &attrs, &schema_crate)?;

        // A field is optional when it says so, or when its type is `Option<...>`: an `Option` that
        // still claimed `required` would make a client send null rather than omitting the field.
        let is_option = is_option(ty);
        let optional = attrs.optional || is_option;

        let docs = doc_string(&field.attrs);
        let added_in = attrs.added_in;

        let constructor = if optional {
            quote!(#schema_crate::Field::optional(#wire_name, #base))
        } else {
            quote!(#schema_crate::Field::required(#wire_name, #base))
        };

        let mut builder = quote!(#constructor);
        if let Some(revision) = added_in {
            builder = quote!(#builder.added_in(#revision));
        }
        if let Some(docs) = docs {
            builder = quote!(#builder.with_docs(#docs));
        }

        field_tokens.push(builder);
    }

    let added_in = container.added_in;
    let docs = doc_string(&input.attrs);

    let mut object = quote! {
        #schema_crate::ObjectSchema::new(#schema_name, vec![#(#field_tokens),*])
    };
    if let Some(revision) = added_in {
        // `ObjectSchema` has no builder method for this yet; setting the field directly keeps the
        // generated code honest about what exists.
        object = quote! {
            {
                let mut schema = #object;
                schema.added_in = Some(#revision);
                schema
            }
        };
    }
    if let Some(docs) = docs {
        object = quote! {
            {
                let mut schema = #object;
                schema.docs = Some(#docs.to_owned());
                schema
            }
        };
    }

    // The generated function returns the schema rather than implementing a trait: a trait impl would
    // force every type to pick one representation, while a value lets a caller render it at any
    // revision and lets a test compare it against a hand-written reference.
    Ok(quote! {
        impl #struct_name {
            /// This type's schema, generated by `#[derive(Typert)]`.
            #[must_use]
            pub fn typert_schema() -> #schema_crate::ObjectSchema {
                #object
            }
        }
    })
}

/// Maps a type to a schema, for the attribute macro.
///
/// A different entry point from `schema_for_type` because an attribute sees a `Box<Type>` rather
/// than the same shape a field does, and because this path has no field attributes to consult.
pub fn schema_for_public_type(
    ty: &syn::Type,
    schema_crate: &TokenStream2,
) -> syn::Result<TokenStream2> {
    // `&str` and `&T` are references; the wire carries the value, not the borrow.
    if let syn::Type::Reference(reference) = ty {
        return schema_for_public_type(&reference.elem, schema_crate);
    }
    // A trait object or a function pointer has no schema a client can use.
    schema_for_type(ty, &TypertAttrs::default(), schema_crate)
}

/// Maps a Rust type to a schema.
fn schema_for_type(
    ty: &syn::Type,
    attrs: &TypertAttrs,
    schema_crate: &TokenStream2,
) -> syn::Result<TokenStream2> {
    let _ = attrs;
    if let Some(inner) = option_inner(ty) {
        let inner_schema = schema_for_type(inner, attrs, schema_crate)?;
        return Ok(quote!(#schema_crate::Schema::Optional(Box::new(#inner_schema))));
    }
    if let Some(inner) = vec_inner(ty) {
        let inner_schema = schema_for_type(inner, attrs, schema_crate)?;
        return Ok(quote!(#schema_crate::Schema::Array(Box::new(#inner_schema))));
    }
    // A JSON object map. Recognised rather than left to become a `Ref`: a reference to `Map` would
    // name a type no client has, and the schema would silently describe nothing.
    if let Some(value) = map_value(ty) {
        let value_schema = schema_for_type(value, attrs, schema_crate)?;
        return Ok(quote!(#schema_crate::Schema::Map(Box::new(#value_schema))));
    }

    let syn::Type::Path(path) = ty else {
        return Err(syn::Error::new_spanned(
            ty,
            "Typert cannot describe this type; use a named type or a supported container",
        ));
    };
    let Some(segment) = path.path.segments.last() else {
        return Err(syn::Error::new_spanned(ty, "empty type path"));
    };
    let name = segment.ident.to_string();
    Ok(match name.as_str() {
        "String" | "str" => quote!(#schema_crate::Schema::String),
        "bool" => quote!(#schema_crate::Schema::Bool),
        "u8" | "u16" | "u32" | "u64" | "i8" | "i16" | "i32" | "i64" | "usize" | "isize" => {
            quote!(#schema_crate::Schema::Int64)
        }
        "f32" | "f64" => quote!(#schema_crate::Schema::Float64),
        "Value" => quote!(#schema_crate::Schema::Any),
        // Anything else is a named type that must itself derive Typert; referencing it rather than
        // inlining keeps one definition in one place.
        other => {
            let _ = other;
            quote!(#schema_crate::Schema::Ref(String::from(#name)))
        }
    })
}

/// The inner type of `Option<T>`.
fn option_inner(ty: &syn::Type) -> Option<&syn::Type> {
    single_generic_arg(ty, "Option")
}

/// The element type of `Vec<T>`.
fn vec_inner(ty: &syn::Type) -> Option<&syn::Type> {
    single_generic_arg(ty, "Vec")
}

/// The single type argument of a one-parameter container.
fn single_generic_arg<'a>(ty: &'a syn::Type, container: &str) -> Option<&'a syn::Type> {
    let syn::Type::Path(path) = ty else {
        return None;
    };
    let segment = path.path.segments.last()?;
    if segment.ident != container {
        return None;
    }
    let syn::PathArguments::AngleBracketed(args) = &segment.arguments else {
        return None;
    };
    if args.args.len() != 1 {
        return None;
    }
    match args.args.first()? {
        syn::GenericArgument::Type(inner) => Some(inner),
        _ => None,
    }
}

/// The value type of a `Map<String, V>`.
fn map_value(ty: &syn::Type) -> Option<&syn::Type> {
    let syn::Type::Path(path) = ty else {
        return None;
    };
    let segment = path.path.segments.last()?;
    if segment.ident != "Map" {
        return None;
    }
    let syn::PathArguments::AngleBracketed(args) = &segment.arguments else {
        return None;
    };
    // The first argument is the key; the wire only ever uses string keys, so a map with a different
    // key type is not something a schema can express.
    match args.args.iter().nth(1)? {
        syn::GenericArgument::Type(value) => Some(value),
        _ => None,
    }
}

/// Whether a type is `Option<...>`.
fn is_option(ty: &syn::Type) -> bool {
    option_inner(ty).is_some()
}

/// Parses `#[typert(...)]` attributes.
fn parse_attrs(attrs: &[syn::Attribute]) -> syn::Result<TypertAttrs> {
    let mut parsed = TypertAttrs::default();
    for attr in attrs {
        if !attr.path().is_ident("typert") {
            continue;
        }
        attr.parse_nested_meta(|meta| {
            if meta.path.is_ident("name") {
                let value: LitStr = meta.value()?.parse()?;
                parsed.name = Some(value.value());
                Ok(())
            } else if meta.path.is_ident("rename") {
                let value: LitStr = meta.value()?.parse()?;
                parsed.rename = Some(value.value());
                Ok(())
            } else if meta.path.is_ident("added_in") {
                let value: LitInt = meta.value()?.parse()?;
                parsed.added_in = Some(value.base10_parse()?);
                Ok(())
            } else if meta.path.is_ident("optional") {
                parsed.optional = true;
                Ok(())
            } else {
                Err(meta.error("unknown typert attribute"))
            }
        })?;
    }
    Ok(parsed)
}

/// The `///` documentation of an item, joined.
fn doc_string(attrs: &[syn::Attribute]) -> Option<String> {
    let mut lines = Vec::new();
    for attr in attrs {
        if !attr.path().is_ident("doc") {
            continue;
        }
        if let syn::Meta::NameValue(pair) = &attr.meta
            && let syn::Expr::Lit(syn::ExprLit {
                lit: syn::Lit::Str(text),
                ..
            }) = &pair.value
        {
            lines.push(text.value().trim().to_owned());
        }
    }
    if lines.is_empty() {
        None
    } else {
        Some(lines.join(" "))
    }
}

/// Expands an enum into a discriminated union.
///
/// Each variant becomes one branch whose `kind` field is fixed to the variant's tag, so a client can
/// narrow without checking anything else. A variant with fields carries them as that branch's object
/// properties; a unit variant carries only its tag.
fn expand_enum(
    input: &DeriveInput,
    data: &syn::DataEnum,
    container: &TypertAttrs,
    schema_crate: &TokenStream2,
) -> syn::Result<TokenStream2> {
    let enum_name = &input.ident;
    let schema_name = container
        .name
        .clone()
        .unwrap_or_else(|| enum_name.to_string());

    let mut branches = Vec::new();
    for variant in &data.variants {
        let variant_attrs = parse_attrs(&variant.attrs)?;
        let tag = variant_attrs
            .rename
            .clone()
            .unwrap_or_else(|| default_tag(&variant.ident.to_string()));

        let mut fields = Vec::new();
        match &variant.fields {
            Fields::Unit => {}
            Fields::Named(named) => {
                for field in &named.named {
                    fields.push(field_tokens(field, schema_crate)?);
                }
            }
            Fields::Unnamed(_) => {
                // A tuple variant has no field names, so there is nothing to put on the wire. Naming
                // them `0`, `1` would produce a schema no client could interpret.
                return Err(syn::Error::new_spanned(
                    &variant.ident,
                    "Typert needs named fields inside an enum variant; a tuple variant has no field names",
                ));
            }
        }

        // The branch object is named after the variant so its `$ref` target is legible.
        let branch_name = format!("{schema_name}{}", variant.ident);
        let docs = doc_string(&variant.attrs);
        let mut object = quote! {
            #schema_crate::ObjectSchema::new(#branch_name, vec![#(#fields),*])
        };
        if let Some(docs) = docs {
            object = quote! {
                {
                    let mut schema = #object;
                    schema.docs = Some(#docs.to_owned());
                    schema
                }
            }
        }

        branches.push(quote! {
            #schema_crate::Variant {
                tag: #tag.to_owned(),
                schema: #schema_crate::Schema::Object(#object),
            }
        });
    }

    Ok(quote! {
        impl #enum_name {
            /// This type's schema, generated by `#[derive(Typert)]`.
            ///
            /// A discriminated union: every branch constrains the tag, so a client can narrow on it
            /// without inspecting the rest of the object.
            #[must_use]
            pub fn typert_schema() -> #schema_crate::Schema {
                #schema_crate::Schema::OneOf(vec![#(#branches),*])
            }
        }
    })
}

/// The wire tag for a variant when it is not renamed.
///
/// The Rust name in kebab-case, matching the event tags this codebase already writes: a client reads
/// `turn-end`, not `TurnEnd`.
fn default_tag(rust_name: &str) -> String {
    let mut tag = String::new();
    for (index, character) in rust_name.chars().enumerate() {
        if character.is_uppercase() {
            if index > 0 {
                tag.push('-');
            }
            for lower in character.to_lowercase() {
                tag.push(lower);
            }
        } else {
            tag.push(character);
        }
    }
    tag
}

/// Builds one field of a variant.
fn field_tokens(field: &syn::Field, schema_crate: &TokenStream2) -> syn::Result<TokenStream2> {
    let attrs = parse_attrs(&field.attrs)?;
    let ident = field.ident.as_ref().expect("named fields have identifiers");
    let wire_name = attrs.rename.clone().unwrap_or_else(|| ident.to_string());

    let ty = &field.ty;
    let base = schema_for_type(ty, &attrs, schema_crate)?;
    let optional = attrs.optional || is_option(ty);

    let constructor = if optional {
        quote!(#schema_crate::Field::optional(#wire_name, #base))
    } else {
        quote!(#schema_crate::Field::required(#wire_name, #base))
    };

    let mut builder = quote!(#constructor);
    if let Some(revision) = attrs.added_in {
        builder = quote!(#builder.added_in(#revision));
    }
    if let Some(docs) = doc_string(&field.attrs) {
        builder = quote!(#builder.with_docs(#docs));
    }
    Ok(builder)
}
