//! Expansion of `#[remote]`.
//!
//! An attribute macro **replaces** the item it decorates, so this one must emit the original
//! function back out. Forgetting that is the classic way to make a function vanish: the code
//! compiles, the item is simply gone, and the error appears wherever it was called.
//!
//! # What it generates
//!
//! 1. The original function, unchanged.
//! 2. An inherent method returning this function's [`Method`] description, so a catalogue can be
//!    assembled without a second, hand-maintained list of signatures.

use proc_macro2::TokenStream as TokenStream2;
use quote::quote;
use syn::{ItemFn, LitStr, parse_macro_input};

use crate::derive::schema_for_public_type;
use crate::schema_path::schema_crate;

/// Expands the attribute.
pub fn expand(
    attr: proc_macro::TokenStream,
    item: proc_macro::TokenStream,
) -> proc_macro::TokenStream {
    let function = parse_macro_input!(item as ItemFn);
    match expand_inner(attr.into(), &function) {
        Ok(tokens) => tokens.into(),
        Err(error) => {
            // On failure the original function is still emitted, so the caller sees the macro's error
            // rather than a cascade of "function not found" at every call site.
            let original = &function;
            let error = error.to_compile_error();
            quote!(#original #error).into()
        }
    }
}

/// Parses `#[remote(namespace = "...", name = "...")]`.
fn expand_inner(attr: TokenStream2, function: &ItemFn) -> syn::Result<TokenStream2> {
    let schema_crate = schema_crate();

    let mut namespace: Option<String> = None;
    let mut name: Option<String> = None;

    let parser = syn::meta::parser(|meta| {
        if meta.path.is_ident("namespace") {
            let value: LitStr = meta.value()?.parse()?;
            namespace = Some(value.value());
            Ok(())
        } else if meta.path.is_ident("name") {
            let value: LitStr = meta.value()?.parse()?;
            name = Some(value.value());
            Ok(())
        } else {
            Err(meta.error("unknown remote attribute; expected `namespace` or `name`"))
        }
    });
    syn::parse::Parser::parse2(parser, attr)?;

    let fn_name = &function.sig.ident;
    let namespace = namespace.ok_or_else(|| {
        syn::Error::new_spanned(
            fn_name,
            "`#[remote]` needs a namespace, as in `#[remote(namespace = \"session\")]`",
        )
    })?;
    let wire_name = name.unwrap_or_else(|| fn_name.to_string());
    let docs = doc_string(&function.attrs);

    // Parameters: every argument except a receiver. A `&self` receiver is not part of the wire
    // signature -- it names the object the method belongs to, which the namespace already carries.
    let mut parameters = Vec::new();
    for argument in &function.sig.inputs {
        let syn::FnArg::Typed(typed) = argument else {
            continue;
        };
        let syn::Pat::Ident(pattern) = typed.pat.as_ref() else {
            return Err(syn::Error::new_spanned(
                &typed.pat,
                "`#[remote]` needs simple parameter names; a destructuring pattern has no wire name",
            ));
        };
        let parameter_name = pattern.ident.to_string();
        let schema = schema_for_public_type(&typed.ty, &schema_crate)?;
        parameters.push(quote! {
            #schema_crate::Parameter::required(#parameter_name, #schema)
        });
    }

    let returns = match &function.sig.output {
        syn::ReturnType::Default => quote!(#schema_crate::Schema::Any),
        syn::ReturnType::Type(_, ty) => schema_for_public_type(ty, &schema_crate)?,
    };

    let mut method = quote! {
        #schema_crate::Method::new(#namespace, #wire_name)
            #(.with_parameter(#parameters))*
            .returning(#returns)
    };
    if let Some(docs) = docs {
        method = quote!(#method.with_docs(#docs));
    }

    // A free function cannot carry an inherent method: `impl <fn name>` would name a type that does
    // not exist. So the descriptor becomes a `const` beside the function, which works at any scope
    // and cannot collide with an existing impl block.
    let descriptor_name = syn::Ident::new(
        &format!("{}_REMOTE_METHOD", fn_name.to_string().to_uppercase()),
        fn_name.span(),
    );

    Ok(quote! {
        #function

        /// This method's wire descriptor, generated by `#[remote]`.
        #[allow(non_upper_case_globals, reason = "named after the function it describes")]
        pub const #descriptor_name: fn() -> #schema_crate::Method = || {
            #method
        };
    })
}

/// The `///` documentation of an item, joined.
fn doc_string(attrs: &[syn::Attribute]) -> Option<String> {
    let mut lines = Vec::new();
    for attr in attrs {
        if !attr.path().is_ident("doc") {
            continue;
        }
        if let syn::Meta::NameValue(pair) = &attr.meta
            && let syn::Expr::Lit(syn::ExprLit {
                lit: syn::Lit::Str(text),
                ..
            }) = &pair.value
        {
            lines.push(text.value().trim().to_owned());
        }
    }
    if lines.is_empty() {
        None
    } else {
        Some(lines.join(" "))
    }
}
