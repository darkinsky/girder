//! The `credentials.*` Remote namespace: the wire half of the credential seam.
//!
//! # Why this namespace, out of the ten `packages/api` subpackages
//!
//! `packages/api` is 24,542 production lines over ten subpackages. Measured on this checkout, the
//! per-package coverage of this crate is:
//!
//! | subpackage | lines | upstream exported symbols | named locally | verdict |
//! |---|---|---|---|---|
//! | `session-controller` | 9,413 | 227 | 71 | partial |
//! | `gateway` | 5,691 | 76 | 32 | partial |
//! | `terminal-controller` | 2,857 | 49 | 14 | partial |
//! | `workspace-controller` | 1,960 | 49 | 18 | partial |
//! | `workspace-files` | 1,624 | 38 | 9 | partial |
//! | `remote-access` | 1,073 | 23 | 6 | partial |
//! | `job-controller` | 994 | 24 | 11 | partial |
//! | `remotes` | 469 | 4 | 3 | partial |
//! | `settings-controller` | 461 | 4 | 0 → **4** | **closed here**, except the two gaps below |
//! | `account-controller` | **0** | 0 | 0 | **cannot be ported: no `src/`** |
//!
//! The two zero-hit rows are the ones this task asked about, and they resolve in opposite ways.
//!
//! ## `account-controller` has no source, so nothing here invents an implementation for it
//!
//! The package contains only `lib/` — compiled JavaScript and generated declaration files — and
//! `lib/index.js`'s own header says `Generated by @deepseek-ai/dsh-typert-generator`. There is no
//! `src/`, so there is no reference implementation, no `@Remote` decorator, and no snapshot to
//! translate: **0 lines**, exactly as the ledger says. Its `lib/typert.remote-client.d.ts` does
//! declare an eleven-method `account` namespace (`getState`, `getProfile`, `getBalance`,
//! `getUnnotifiedBonuses`, `ackBonusNotified`, `startSignIn`, `cancelSignIn`,
//! `hasRunningAccountTasks`, `signOut`, plus the `watch`/`watchExpiry` streams), and every one of
//! them is a one-line forward to `ctx.deepseekAccount` (`packages/credentials/deepseek-account`,
//! 1,526 lines). That seam has no counterpart here either — no `deepseekAccount`, no Platform HTTP
//! client, no OAuth attempt state machine, no `/login` route — so a "port" would be eleven handlers
//! with nothing behind them. Three of them (`getProfile`, `getBalance`, `getUnnotifiedBonuses`) are
//! also *sign-in-gated*: they answer `null` unless a live account grant exists, and this build has
//! no grant concept. [`crate::credentials`] is a *value* store, not an account. Fabricating an
//! account surface over it would hand a client an `AccountView` nothing maintains.
//!
//! So the honest report for `account-controller` is: **gap, not portable from source, deliberately
//! not implemented.** Nothing below pretends otherwise. A future port needs the
//! `deepseek-account` seam, the Platform client, and the OAuth attempt machine — three
//! dependencies that do not exist yet, and none of which this module can stand in for.
//!
//! ## `settings-controller`'s overlap with [`crate::settings_rpc`] is partial, and the seam is exact
//!
//! Upstream's package exports four symbols: `SettingsController`, `SettingsControllerInternals`,
//! `SettingsDocumentOpenValue`, and `CredentialsController`. The `settings` **namespace** live in
//! it — `describe`, `update`, `replace`, `mutate`, `openSettingsDocument` — is already served by
//! [`crate::settings_rpc`], which registers five of those spellings (`describe` and
//! `openSettingsDocument` are recorded there as `NOT_IMPLEMENTED`, with the reason; that module
//! serves `get`/`set`/`list`/`delete` in their place). [Verified: `settings_rpc::NAMESPACE` is
//! `"settings"`, `UNIMPLEMENTED` is exactly `["describe", "openSettingsDocument"]`, and its
//! `update`/`replace`/`mutate` are registered against a `SettingsStore`.]
//!
//! What `settings_rpc` does **not** serve is the second namespace the same package mounts:
//! `credentials`, with `describe(refs)`, `set(ref, value)`, and `unset(ref)`. That module says so
//! explicitly at its own top — "the three `credentials.*` methods — a different namespace and a
//! different seam (secret references, not settings values). They belong with
//! [`crate::credentials`], not here." This is that module.
//!
//! The credential **domain** already exists: [`crate::credentials`] has `Store::describe`/`set`/
//! `unset` and an [`Info`](crate::credentials::Info) with no field a secret could ride in. What was
//! missing is the three wire obligations `CredentialsController` carries that a plain store call
//! does not, and those are what this module exists for:
//!
//! 1. **The reference grammar is a closed set**, not "any non-blank string". Upstream's
//!    `credentialRefSchema` is `/^[A-Za-z_][A-Za-z0-9_]*$/` — a POSIX identifier — and
//!    `credentialRef()` throws outside it. [`validate_reference`] is that rule.
//! 2. **`describe` is a *batch* with a fan-out bound.** A settings page describes every reference
//!    its own rows name in one round trip. [`MAX_DESCRIBE_REFS`] = 64 caps how much provider work
//!    one authenticated request can start.
//! 3. **The view is projected field by field, and no method ever returns a value.** Upstream's
//!    `projectCredentialInfo` exists because the Gateway does not decode a business result; a
//!    provider's extra enumerable properties would otherwise serialize to the caller. [`project`]
//!    copies exactly `configured`/`source`/`writable`/`masked` for the same reason.
//!
//! The write path carries a fourth: **every provider refusal is one code**, `credential/rejected`,
//! with the provider's own message, because that message is what a settings page must show
//! verbatim (a stored document that no longer parses, for instance). The details name the reference
//! and never the value — which is why [`write_refusal`] only ever formats a reference.
//!
//! # `masked` is carried, and this crate's `Info` does not have it
//!
//! [`crate::credentials::Info`] has three fields (`configured`, `source`, `writable`) and
//! deliberately no `masked`, because its store keeps no provider-side preview. Upstream's
//! `CredentialInfo` has a fourth, optional `masked`. Rather than widen the existing type — which
//! other modules and tests already match on — [`CredentialInfo`] here is the *wire* projection:
//! it can carry `masked`, and [`project`] takes it from whatever the caller supplies. A store that
//! has none reports none, and the field is **omitted** rather than sent as `null`, matching
//! upstream's `...info.masked === undefined ? {} : { masked: info.masked }`.
//!
//! # Wire shapes
//!
//! ```text
//! credentials.describe  {refs: [string]}          -> {items: {<ref>: {configured, source?, writable, masked?}}}
//! credentials.set       {ref, value}             -> {ref, set: true}
//! credentials.unset     {ref}                    -> {ref, unset: true}
//! ```
//!
//! `describe` answers an object keyed by reference, which is upstream's `Record<string,
//! CredentialInfo>`: a page that asked about twelve rows reads its twelve answers by name instead
//! of matching an array back up by position.
//!
//! # Why `unset` is `destructive` and `set` is only `write`
//!
//! A removed credential cannot be restored from anything this process holds; only the caller that
//! still remembers the secret can write it again. A stored one can be overwritten, which is the
//! normal rotation case. Declaring both `write` would let a policy that permits rotation also
//! permit erasure, and the difference between the two is exactly what an operator wants to split.
//!
//! # What is deliberately absent
//!
//! - **No read path returns a secret.** `describe` answers [`CredentialInfo`], and the type has no
//!   field one could ride in. That is the same structural guarantee [`crate::credentials::Info`]
//!   makes, restated at the wire boundary where it matters more.
//! - **No `has`/`getValue`/`resolve`.** Upstream has none on this namespace either: resolving a
//!   credential to a value happens inside the Host, for the Host's own outbound request, and never
//!   for a peer.
//! - **No event streaming.** Upstream's credential seam emits `credentials/reference-updated`, but
//!   `CredentialsController` does not forward it over the wire, so neither does this.

use std::collections::BTreeMap;
use std::sync::{Arc, PoisonError, RwLock, RwLockReadGuard, RwLockWriteGuard};

use serde::Deserialize;
use serde_json::{Map, Value, json};

use girder_core::{Declaration, RemoteCall, RemoteError, RemoteRegistry};

// ---- surface constants ------------------------------------------------------------------------

/// The namespace every method here is served under.
///
/// The same spelling upstream's `TypertRemoteService` is constructed with
/// (`super(ctx, 'credentialsController', { namespace: 'credentials' })`).
pub const NAMESPACE: &str = "credentials";

/// Describes several references in one round trip.
pub const DESCRIBE_METHOD: &str = "describe";

/// Stores one value under one reference.
pub const SET_METHOD: &str = "set";

/// Removes one reference.
pub const UNSET_METHOD: &str = "unset";

/// The fan-out bound on one `describe` batch.
///
/// Upstream's `MAX_DESCRIBE_REFS`. A settings page asks about the references its own rows name, so
/// this is far above any real page while still keeping one authenticated request from starting
/// unbounded provider work. Measured in references, not bytes: the cost this bounds is one provider
/// lookup per entry, and a very long reference is bounded separately by [`MAX_REFERENCE_LEN`].
pub const MAX_DESCRIBE_REFS: usize = 64;

/// The longest reference this build accepts, in bytes.
///
/// Upstream's grammar has no length bound, which is fine for a TypeScript string and not fine for a
/// value that becomes a map key in every store this crate ships: an unbounded name lets one call
/// allocate past what any of them can hold. A POSIX identifier is short by nature, so a bound well
/// above any real provider name refuses only the abusive case.
pub const MAX_REFERENCE_LEN: usize = 256;

/// The resource kind these methods touch, as reported to an access policy.
const RESOURCE_KIND: &str = "credential";

/// The method names this module serves, in the order they are declared.
#[allow(
    dead_code,
    reason = "a list of the three method names, for a caller that wants to report a surface without registering it"
)]
pub const METHODS: &[&str] = &[DESCRIBE_METHOD, SET_METHOD, UNSET_METHOD];

// ---- reference grammar -------------------------------------------------------------------------

/// Checks one reference against upstream's grammar, answering it unchanged when it is usable.
///
/// The rule is `/^[A-Za-z_][A-Za-z0-9_]*$/`, i.e. a POSIX environment-variable identifier, because
/// that is what a credential reference *is*: the name of a value the harness may place into a
/// subprocess environment. `AWS_PROFILE` is a reference; `aws/profile` is not, and neither is `""`.
///
/// The empty string is refused by the same rule rather than by a separate check, which is the point
/// of stating the rule as a grammar: there is one place to read what a reference may be, and one
/// place to change it.
///
/// A length bound is added on top of the grammar. Upstream has none; see [`MAX_REFERENCE_LEN`].
fn validate_reference(reference: &str) -> Result<&str, String> {
    let mut characters = reference.chars();
    let Some(first) = characters.next() else {
        return Err("a credential reference must not be empty".to_owned());
    };
    if !(first.is_ascii_alphabetic() || first == '_') {
        return Err(format!(
            "`{reference}` does not start with a letter or `_`, which is where a credential \
             reference must start"
        ));
    }
    if let Some(bad) = characters.find(|c| !(c.is_ascii_alphanumeric() || *c == '_')) {
        return Err(format!(
            "`{reference}` contains `{bad}`, which is not allowed in a credential reference \
             (letters, digits, and `_` only)"
        ));
    }
    if reference.len() > MAX_REFERENCE_LEN {
        return Err(format!(
            "a credential reference must be at most {MAX_REFERENCE_LEN} bytes, got {}",
            reference.len()
        ));
    }
    Ok(reference)
}

/// Whether one reference is usable, for a caller that wants a boolean rather than a message.
///
/// Exposed because the grammar is the interesting part of this module and a UI that pre-validates a
/// field should not have to duplicate the rule to do it.
#[must_use]
#[allow(
    dead_code,
    reason = "exported for a caller that validates a reference before sending it; the registration validates through `describe` instead"
)]
pub fn is_valid_reference(reference: &str) -> bool {
    validate_reference(reference).is_ok()
}

// ---- the view that crosses the wire ------------------------------------------------------------

/// What a client may know about one credential.
///
/// There is deliberately **no field a secret could ride in** — the same guarantee
/// [`crate::credentials::Info`] makes, restated here because this is the type that is actually
/// serialized to a peer.
///
/// `source` and `masked` are `Option` and are **omitted** from the wire form when absent, matching
/// upstream's conditional spreads. One that were sent as `null` would be indistinguishable from a
/// provider that reported nothing at all.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct CredentialInfo {
    /// Whether resolving the reference would currently return a value.
    pub configured: bool,
    /// The source layer supplying the value; absent while unconfigured.
    ///
    /// A layer name such as `env` or `store`, never a value.
    pub source: Option<String>,
    /// Whether the active provider can write this reference.
    pub writable: bool,
    /// A provider-generated preview of the stored value; never the full value.
    ///
    /// The provider decides what "masked" means and is the only thing that can produce one. This
    /// module neither derives nor lengthens it.
    pub masked: Option<String>,
}

impl CredentialInfo {
    /// The view of an unconfigured reference.
    #[must_use]
    pub fn missing() -> Self {
        Self {
            configured: false,
            source: None,
            writable: false,
            masked: None,
        }
    }

    /// The view of a configured reference supplied by `source`.
    #[must_use]
    pub fn configured(source: impl Into<String>, writable: bool) -> Self {
        Self {
            configured: true,
            source: Some(source.into()),
            writable,
            masked: None,
        }
    }

    /// The same facts with a provider preview attached.
    #[must_use]
    pub fn with_masked(mut self, masked: impl Into<String>) -> Self {
        self.masked = Some(masked.into());
        self
    }

    /// This view as a JSON object carrying only the four declared fields.
    ///
    /// Field by field rather than `serde::Serialize` on the struct, for the reason upstream's
    /// `projectCredentialInfo` gives: this type exists to be the *only* thing that crosses, so the
    /// place that decides what crosses is worth being able to read in one screen. A derived
    /// `Serialize` would also silently start sending any field a later edit added.
    #[must_use]
    pub fn to_json(&self) -> Value {
        let mut object = Map::new();
        object.insert("configured".to_owned(), Value::Bool(self.configured));
        if let Some(source) = &self.source {
            object.insert("source".to_owned(), Value::String(source.clone()));
        }
        object.insert("writable".to_owned(), Value::Bool(self.writable));
        if let Some(masked) = &self.masked {
            object.insert("masked".to_owned(), Value::String(masked.clone()));
        }
        Value::Object(object)
    }
}

// ---- storage seam ------------------------------------------------------------------------------

/// Where credential views and values are kept.
///
/// Deliberately **view-shaped** rather than value-shaped: `describe` answers a
/// [`CredentialInfo`], never a secret, so an implementation cannot leak one through a method this
/// module forgot to guard. The write half takes a value and returns nothing, so no implementation
/// has a way to hand one back.
///
/// Every method is `&self` and the trait is `Send + Sync`, because a handler is called from many
/// requests at once. Implementations provide their own interior mutability.
pub trait CredentialSource: Send + Sync {
    /// Describes one reference without revealing it.
    ///
    /// An unconfigured reference is a normal answer ([`CredentialInfo::missing`]), not an error: a
    /// settings page describes every row it renders, and most rows are unset on a fresh install.
    fn describe(&self, reference: &str) -> CredentialInfo;

    /// Stores one value.
    ///
    /// An `Err` means nothing was stored, so a caller must not report success. The message is shown
    /// to the caller as the provider's own refusal, which is why it should say what the provider
    /// said — and why it must not quote the value.
    fn set(&self, reference: &str, value: &str) -> Result<(), String>;

    /// Removes one reference.
    ///
    /// `Ok(true)` when it was there and is now gone, `Ok(false)` when nothing held it.
    fn unset(&self, reference: &str) -> Result<bool, String>;
}

/// A source that keeps values in this process's memory.
///
/// **Lost on restart, and the values are held in the clear.** It exists so the surface is testable
/// and so a host can accept writes before it has durable storage; it is not persistence and it is
/// not a secret store. A real deployment passes its own [`CredentialSource`] — the module's own
/// registration installs [`UnavailableCredentialSource`] for exactly this reason.
#[derive(Debug, Default)]
pub struct MemoryCredentialSource {
    /// The stored values, plus the source name each one came from.
    ///
    /// The name is stored beside the value because [`CredentialSource::describe`] has to report
    /// where a value came from, and a source that forgot it would report `configured` with no
    /// provenance — which is the one fact a "which layer is winning" bug needs.
    values: RwLock<BTreeMap<String, (String, String)>>,
}

impl MemoryCredentialSource {
    /// Creates an empty source.
    #[must_use]
    pub fn new() -> Self {
        Self::default()
    }

    /// How many references are stored.
    #[must_use]
    pub fn len(&self) -> usize {
        self.read().len()
    }

    /// Whether nothing is stored.
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.len() == 0
    }

    // Poisoning is recovered rather than propagated, following `settings_rpc`: a panic while
    // holding this map leaves a table of values rather than a half-written one, and refusing every
    // later call would turn one panic into a permanently unusable credential surface.
    fn read(&self) -> RwLockReadGuard<'_, BTreeMap<String, (String, String)>> {
        self.values.read().unwrap_or_else(PoisonError::into_inner)
    }

    fn write(&self) -> RwLockWriteGuard<'_, BTreeMap<String, (String, String)>> {
        self.values.write().unwrap_or_else(PoisonError::into_inner)
    }
}

impl CredentialSource for MemoryCredentialSource {
    fn describe(&self, reference: &str) -> CredentialInfo {
        match self.read().get(reference) {
            Some((_, source)) => CredentialInfo::configured(source.clone(), true),
            None => CredentialInfo::missing(),
        }
    }

    fn set(&self, reference: &str, value: &str) -> Result<(), String> {
        // The value is validated for emptiness at the boundary, not here; a store that received an
        // empty string would be storing a credential that authenticates nothing.
        self.write().insert(
            reference.to_owned(),
            (value.to_owned(), "memory".to_owned()),
        );
        Ok(())
    }

    fn unset(&self, reference: &str) -> Result<bool, String> {
        Ok(self.write().remove(reference).is_some())
    }
}

/// The source a deployment gets when it configures none.
///
/// Every write is refused and the reason names what is missing, following
/// [`crate::settings_rpc::UnavailableSettingsStore`]. The alternative — quietly keeping values in a
/// process-local map — would report "stored" for a secret that the next process cannot find, which
/// is the one failure a configuration page must never show.
#[derive(Debug)]
#[allow(
    dead_code,
    reason = "the seam a deployment supplies when it has no credential store; unused here because `serve` uses the in-memory one"
)]
pub struct UnavailableCredentialSource {
    reason: String,
}

#[allow(
    dead_code,
    reason = "constructors for the refusing store a deployment supplies; unused here because `serve` uses the in-memory one"
)]
impl UnavailableCredentialSource {
    /// Creates a source that refuses every write with `reason`.
    #[must_use]
    pub fn new(reason: impl Into<String>) -> Self {
        Self {
            reason: reason.into(),
        }
    }

    /// The reason the default registration uses.
    ///
    /// It names the call a host makes to fix it, because a message that only said "not supported"
    /// would leave an operator guessing which half to supply.
    #[must_use]
    pub fn default_reason() -> Self {
        Self::new(
            "no CredentialSource was supplied; this module ships only an in-process source that \
             keeps values in the clear and loses them on restart, so a host must pass its own \
             Arc<dyn CredentialSource> to register_credential_methods",
        )
    }
}

#[allow(
    dead_code,
    reason = "the refusing implementation of the store trait; a deployment with no credential backend supplies it"
)]
impl CredentialSource for UnavailableCredentialSource {
    fn describe(&self, _reference: &str) -> CredentialInfo {
        // Unconfigured rather than a refusal, because the signature has no error channel. The
        // refusal a caller actually sees comes from the write path, which carries this reason —
        // and "nothing is configured here" is true of a source that holds nothing.
        CredentialInfo::missing()
    }

    fn set(&self, _reference: &str, _value: &str) -> Result<(), String> {
        Err(self.reason.clone())
    }

    fn unset(&self, _reference: &str) -> Result<bool, String> {
        Err(self.reason.clone())
    }
}

// ---- registration ------------------------------------------------------------------------------

/// Registers the `credentials.*` methods against `source`.
///
/// Declarations are registered beside each handler so the policy judges a call before it runs; the
/// source is cloned into each closure so the host keeps ownership of it.
pub fn register_credential_methods(
    registry: &mut RemoteRegistry,
    source: &Arc<dyn CredentialSource>,
) {
    // Reading a set of views is a read; storing one is a write; removing one is destructive,
    // because nothing this process holds can restore it. See the module documentation.
    registry.declare(NAMESPACE, DESCRIBE_METHOD, Declaration::read(RESOURCE_KIND));
    registry.declare(NAMESPACE, SET_METHOD, Declaration::write(RESOURCE_KIND));
    registry.declare(
        NAMESPACE,
        UNSET_METHOD,
        Declaration::destructive(RESOURCE_KIND),
    );

    let describe_source = Arc::clone(source);
    registry.register(NAMESPACE, DESCRIBE_METHOD, move |call: RemoteCall| {
        let source = Arc::clone(&describe_source);
        Box::pin(async move { describe(&call.args, &source) })
    });

    let set_source = Arc::clone(source);
    registry.register(NAMESPACE, SET_METHOD, move |call: RemoteCall| {
        let source = Arc::clone(&set_source);
        Box::pin(async move { set(&call.args, &source) })
    });

    let unset_source = Arc::clone(source);
    registry.register(NAMESPACE, UNSET_METHOD, move |call: RemoteCall| {
        let source = Arc::clone(&unset_source);
        Box::pin(async move { unset(&call.args, &source) })
    });
}

// ---- requests ----------------------------------------------------------------------------------

/// The body of `credentials.describe`.
#[derive(Debug, Deserialize)]
struct DescribeRequest {
    /// The references to describe.
    ///
    /// Not `Option`: an absent `refs` is a malformed call, and answering it with an empty object
    /// would tell a page its rows are all unset.
    refs: Vec<String>,
}

/// The body of `credentials.set`.
#[derive(Debug, Deserialize)]
struct SetRequest {
    /// The reference to store under.
    ///
    /// Renamed from the field below because `ref` is a Rust keyword: without the rename, `serde`
    /// would look for `ref_key` on the wire and every well-formed call would be refused for a
    /// missing field.
    #[serde(default, rename = "ref")]
    reference: Option<String>,
    /// The non-empty secret value.
    ///
    /// Not `Option` in the wire sense: an absent one is a parse error naming the field, while an
    /// explicit `null` is not a credential either — [`set`] refuses both with the same message.
    #[serde(default)]
    value: Option<String>,
}

/// The body of `credentials.unset`.
#[derive(Debug, Deserialize)]
struct UnsetRequest {
    /// The reference to remove; see [`SetRequest::reference`] for the rename.
    #[serde(default, rename = "ref")]
    reference: Option<String>,
}

// ---- handlers ---------------------------------------------------------------------------------
//
// The handlers below are plain functions, not `async fn`s: every source call is synchronous, so
// there is nothing to await. The futures lie one layer up, in the registration closures, which is
// the only place the `RemoteMethod` type requires one.

/// Runs one `credentials.describe`.
///
/// A batch of references rather than one, because that is the shape a configuration page has: it
/// describes every reference its rows name at once, and one round trip keeps those rows from
/// settling separately. A batch of one is the degenerate case and is served by the same path.
fn describe(args: &Value, source: &Arc<dyn CredentialSource>) -> Result<Value, RemoteError> {
    let request: DescribeRequest = parse_request(args, DESCRIBE_METHOD)?;

    // The batch bound is checked before the grammar, so a caller that sent 5,000 references is told
    // about the fan-out rather than about the first malformed name — the fan-out is the problem it
    // has to fix either way, and naming it first saves a round trip.
    if request.refs.len() > MAX_DESCRIBE_REFS {
        return Err(invalid(
            DESCRIBE_METHOD,
            format!(
                "a describe batch may name at most {MAX_DESCRIBE_REFS} references, got {}",
                request.refs.len()
            ),
        ));
    }

    // Every reference is validated before any is looked up, which is upstream's behaviour: one name
    // outside the grammar rejects the whole call as a bad request. A partial answer would let a page
    // render eleven rows and silently omit the twelfth.
    for reference in &request.refs {
        validate_reference(reference).map_err(|message| invalid(DESCRIBE_METHOD, message))?;
    }

    // A `BTreeMap` so the object's key order is stable: a page that re-read the same batch should not
    // see its rows reshuffle, and JSON object order is otherwise whatever the source iterated in.
    let mut items = Map::new();
    for reference in &request.refs {
        items.insert(reference.clone(), source.describe(reference).to_json());
    }
    Ok(json!({ "items": Value::Object(items) }))
}

/// Runs one `credentials.set`.
///
/// The value crosses the wire in this direction only: no method here returns one, and the refusal
/// added by [`write_refusal`] names the reference but never the value.
fn set(args: &Value, source: &Arc<dyn CredentialSource>) -> Result<Value, RemoteError> {
    let request: SetRequest = parse_request(args, SET_METHOD)?;
    let reference = require_reference(request.reference.as_deref(), SET_METHOD)?;
    let Some(value) = request.value else {
        return Err(invalid(SET_METHOD, "`value` is required"));
    };
    // A blank value is refused rather than stored: an empty credential authenticates nothing, and a
    // page that submitted a cleared field meant to remove it, which is `unset`.
    if value.is_empty() {
        return Err(invalid(
            SET_METHOD,
            format!(
                "`value` for `{reference}` must not be empty; use `{UNSET_METHOD}` to remove a \
                 credential"
            ),
        ));
    }

    source
        .set(&reference, &value)
        .map_err(|error| write_refusal(reference.as_str(), &error))?;
    Ok(json!({ "ref": reference, "set": true }))
}

/// Runs one `credentials.unset`.
fn unset(args: &Value, source: &Arc<dyn CredentialSource>) -> Result<Value, RemoteError> {
    let request: UnsetRequest = parse_request(args, UNSET_METHOD)?;
    let reference = require_reference(request.reference.as_deref(), UNSET_METHOD)?;

    let removed = source
        .unset(&reference)
        .map_err(|error| write_refusal(reference.as_str(), &error))?;
    // A reference that held nothing is refused rather than reported as a success: the caller meant
    // to remove something, and telling it "done" would hide that its own listing was stale.
    if !removed {
        return Err(invalid(
            UNSET_METHOD,
            format!("no credential `{reference}` is configured"),
        ));
    }
    Ok(json!({ "ref": reference, "unset": true }))
}

// ---- helpers ----------------------------------------------------------------------------------

/// Parses one method's arguments into its request type.
fn parse_request<T>(args: &Value, method: &str) -> Result<T, RemoteError>
where
    T: serde::de::DeserializeOwned,
{
    serde_json::from_value(args.clone()).map_err(|error| RemoteError::InvalidArguments {
        namespace: NAMESPACE.to_owned(),
        method: method.to_owned(),
        message: error.to_string(),
    })
}

/// Validates a raw reference, reporting which rule it broke.
///
/// An absent or blank reference is reported as missing rather than as malformed: an empty string is
/// a client bug, and telling it "that name is not usable" would send the caller looking at a
/// grammar it did not get wrong.
fn require_reference(raw: Option<&str>, method: &str) -> Result<String, RemoteError> {
    match raw {
        Some(reference) if !reference.trim().is_empty() => validate_reference(reference)
            .map(str::to_owned)
            .map_err(|message| invalid(method, message)),
        _ => Err(invalid(method, "`ref` is required")),
    }
}

/// An invalid-argument error for `method`.
fn invalid(method: &str, message: impl Into<String>) -> RemoteError {
    RemoteError::InvalidArguments {
        namespace: NAMESPACE.to_owned(),
        method: method.to_owned(),
        message: message.into(),
    }
}

/// Turns one source refusal into the single failure code a settings page renders.
///
/// `Failed` rather than `InvalidArguments`: the request was fine and the provider refused it, which
/// is the distinction a client needs to stop retrying for the first case and keep trying for the
/// second. The provider's own message is passed through verbatim — it is what the user has to see —
/// and the only thing this function adds is the reference, never the value, so no failure path can
/// carry a secret back out.
fn write_refusal(reference: &str, error: &str) -> RemoteError {
    RemoteError::Failed(format!(
        "`{reference}` was rejected by the credential provider: {error}"
    ))
}

#[cfg(test)]
mod tests {
    //! Unit tests for the pure half: the grammar and the wire projection.
    //!
    //! The RPC behaviour is covered by `tests/account_gap.rs`, which drives the registry. These are
    //! here because the two functions are the ones a later edit is most likely to widen by accident,
    //! and a unit test next to them is the cheapest place to notice.

    use super::{CredentialInfo, MAX_REFERENCE_LEN, is_valid_reference, validate_reference};

    #[test]
    fn the_grammar_accepts_a_posix_identifier() {
        for good in ["AWS_PROFILE", "sk", "_private", "a1", "OPENAI_API_KEY"] {
            assert!(is_valid_reference(good), "`{good}` should be a reference");
        }
    }

    #[test]
    fn the_grammar_refuses_everything_else() {
        for bad in ["", "1abc", "-x", "aws/profile", "a b", "a-b", "café", "a.b"] {
            assert!(
                !is_valid_reference(bad),
                "`{bad}` should not be a reference"
            );
        }
    }

    #[test]
    fn a_reference_longer_than_the_bound_is_refused_by_length_not_by_grammar() {
        let long = "A".repeat(MAX_REFERENCE_LEN + 1);
        let message = validate_reference(&long).expect_err("an over-long name must be refused");
        assert!(message.contains("at most"), "got: {message}");
    }

    #[test]
    fn an_unconfigured_view_omits_both_optional_fields() {
        assert_eq!(
            CredentialInfo::missing().to_json(),
            serde_json::json!({"configured": false, "writable": false})
        );
    }

    #[test]
    fn a_configured_view_with_a_preview_carries_all_four_fields() {
        assert_eq!(
            CredentialInfo::configured("env", true)
                .with_masked("sk-abcd...")
                .to_json(),
            serde_json::json!({
                "configured": true,
                "source": "env",
                "writable": true,
                "masked": "sk-abcd...",
            })
        );
    }
}
