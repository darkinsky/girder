#[test]
fn parse_env_matches_node_util_parse_env() {
    let mut checked = 0usize;
    for (document, expected) in PARSE_ENV_CASES {
        let actual = parse_env(document);
        let expected: BTreeMap<String, String> = expected
            .iter()
            .map(|(key, value)| ((*key).to_owned(), (*value).to_owned()))
            .collect();
        assert_eq!(
            actual, expected,
            "document {document:?} parsed differently from Node"
        );
        checked += 1;
    }
    assert_eq!(checked, PARSE_ENV_CASES.len());
}

#[test]
fn parse_env_keeps_declaration_order() {
    // The order is observable: a refused name is reported in the order the file wrote it.
    let ordered = boot_app_gap::parse_env_ordered("Z=1\nA=2\nM=3\n");
    assert_eq!(
        ordered,
        vec![
            ("Z".to_owned(), "1".to_owned()),
            ("A".to_owned(), "2".to_owned()),
            ("M".to_owned(), "3".to_owned()),
        ]
    );
    // A duplicate keeps its first position and takes the last value, as assigning into an object does.
    let ordered = boot_app_gap::parse_env_ordered("B=1\nA=2\nB=3\n");
    assert_eq!(
        ordered,
        vec![
            ("B".to_owned(), "3".to_owned()),
            ("A".to_owned(), "2".to_owned()),
        ]
    );
}

