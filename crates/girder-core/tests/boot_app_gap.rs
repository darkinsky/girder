/// The inventory `readProfilePlugins` would return for the upstream fixture, with the installed
/// metadata and bundle declarations supplied as the table they were.
fn inventory(
    manifest: &Value,
    dependencies: &[(&str, &str)],
    installed: &[(&str, Option<&str>)],
    bundles: &[&str],
) -> boot_app_gap::ProfilePluginInventory {
    let installed: BTreeMap<&str, Option<&str>> = installed.iter().copied().collect();
    let bundles: Vec<&str> = bundles.to_vec();
    let pairs: Vec<(String, String)> = dependencies
        .iter()
        .map(|(name, spec)| ((*name).to_owned(), (*spec).to_owned()))
        .collect();
    read_profile_plugins(
        manifest,
        &pairs,
        &|name| installed.get(name).copied().flatten().map(str::to_owned),
        &|name| bundles.contains(&name),
    )
}

