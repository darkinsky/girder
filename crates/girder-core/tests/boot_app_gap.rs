/// A failed entry whose detail is `detail`.
fn failed(
    id: &str,
    module: &str,
    required: bool,
    phase: Option<&str>,
    detail: &str,
) -> InactiveEntry {
    InactiveEntry {
        id: id.to_owned(),
        module: module.to_owned(),
        required,
        outcome: InactiveOutcome::Failed {
            phase: phase.map(str::to_owned),
            detail: detail.to_owned(),
        },
    }
}

/// A pending entry waiting for `missing`.
fn pending(id: &str, module: &str, required: bool, missing: &[&str]) -> InactiveEntry {
    InactiveEntry {
        id: id.to_owned(),
        module: module.to_owned(),
        required,
        outcome: InactiveOutcome::Pending {
            missing: missing.iter().map(|name| (*name).to_owned()).collect(),
        },
    }
}

