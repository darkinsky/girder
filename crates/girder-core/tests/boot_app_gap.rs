#[test]
fn an_exemption_records_consent_without_pretending_the_range_was_met() {
    let exemptions =
        BTreeMap::from([("@example/plugin@2.0.0".to_owned(), vec![RUNTIME.to_owned()])]);
    let mut manifest = identity();
    manifest["engines"] = json!({ "dsh": "^0.2.0" });
    let issue = evaluate_plugin_compatibility(&manifest, &exemptions, RUNTIME, &satisfies)
        .expect("well formed")
        .expect("unmet");
    assert!(issue.exempted);
    assert_eq!(
        issue.requirements,
        BTreeMap::from([("engines.dsh".to_owned(), "^0.2.0".to_owned())])
    );
    // The exemption is exact on the plugin name, the plugin version, and the runtime version.
    let mut renamed = identity();
    renamed["name"] = json!("@other/plugin");
    renamed["engines"] = json!({ "dsh": "^0.2.0" });
    assert!(
        !evaluate_plugin_compatibility(&renamed, &exemptions, RUNTIME, &satisfies)
            .expect("well formed")
            .expect("unmet")
            .exempted
    );
    let mut patched = identity();
    patched["version"] = json!("2.0.1");
    patched["engines"] = json!({ "dsh": "^0.2.0" });
    assert!(
        !evaluate_plugin_compatibility(&patched, &exemptions, RUNTIME, &satisfies)
            .expect("well formed")
            .expect("unmet")
            .exempted
    );
    // `0.1.7-alpha.1+build` is a different exact version from `0.1.7-alpha.1`.
    assert!(
        !evaluate_plugin_compatibility(&manifest, &exemptions, "0.1.7-alpha.1+build", &satisfies)
            .expect("well formed")
            .expect("unmet")
            .exempted
    );
    // An exemption value is an exact version, never a range.
    for value in ["*", "^0.1.0", "0.1.7", "0.1.7-alpha.2"] {
        let exemptions =
            BTreeMap::from([("@example/plugin@2.0.0".to_owned(), vec![value.to_owned()])]);
        assert!(
            !evaluate_plugin_compatibility(&manifest, &exemptions, RUNTIME, &satisfies)
                .expect("well formed")
                .expect("unmet")
                .exempted,
            "{value} is not the running version"
        );
    }
}

