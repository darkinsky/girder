#[test]
fn the_home_layer_may_set_route_names_but_not_trust_names() {
    // Proxies, in either spelling, and the endpoints in their exact spelling.
    for accepted in [
        "HTTP_PROXY=http://from-home:8080\n",
        "no_proxy=example.com\n",
        "DEEPSEEK_BASE_URL=https://from-home.example/anthropic\n",
        "DEEPSEEK_SEARCH_BASE_URL=https://from-home.example/v1\n",
    ] {
        let layer = env_layer("/home", "/home", accepted)
            .unwrap_or_else(|error| panic!("{accepted:?} should load: {error}"));
        assert_eq!(layer.path, "/home/.env");
    }
    // A misspelled endpoint would load without effect, so it is refused with a remedy that names the
    // exact spelling.
    let error = env_layer("/home", "/home", "deepseek_base_url=https://x.example/v1\n")
        .expect_err("a misspelled endpoint is refused");
    assert!(
        error
            .to_string()
            .contains("spell it DEEPSEEK_BASE_URL, then export it or put it in /home/.env"),
        "the remedy named the exact spelling: {error}"
    );
    // A trust name stays refused everywhere: it changes what is trusted, not where traffic goes.
    let error = env_layer("/home", "/home", "NODE_TLS_REJECT_UNAUTHORIZED=0\n")
        .expect_err("a trust name is refused in the home layer too");
    assert!(
        error
            .to_string()
            .contains("export NODE_TLS_REJECT_UNAUTHORIZED instead")
    );
}

