#[test]
fn is_semantic_version_matches_node_semver() {
    let valid = [
        "1.2.3",
        "v1.2.3",
        " 1.2.3 ",
        "1.2.3-alpha.1",
        "1.2.3+b",
        "0.0.0",
        "0.1.7-alpha.1",
        "1.2.3-0",
        "1.2.3+a.b",
        "v1.2.3+b",
        "1.2.3-0a",
        "1.2.3+00123",
        "1.2.3-0.0.0",
        "9007199254740991.0.0",
        "1.2.3+a-b",
        "1.2.3--",
    ];
    for version in valid {
        assert!(is_semantic_version(version), "{version:?} should be valid");
    }
    let invalid = [
        "",
        " ",
        "=1.2.3",
        "V1.2.3",
        "=v1.2.3",
        "1.2.3alph",
        "01.2.3",
        "1.2",
        "1",
        "1.2.3.4",
        "1.02.3",
        "1.2.03",
        "1.2.3-01",
        "1.2.3-",
        "1.2.3+",
        "1.2.3-a..b",
        "1.2.3-+b",
        "1.2.3_4",
        "1.2.3-a_b",
        "999999999999999999999.0.0",
        "9007199254740992.0.0",
        "1.2.3-a.01",
        "1.2.3-00",
        "1.2.3+b..c",
        "1.2.3+b_c",
        "v 1.2.3",
        "1.2.3 - 1.2.5",
        "-1.2.3",
        "1.2.3+a+b",
        "1.2.3-0..0",
        "1.2.3-.",
        "..",
        "1.2.3.-0",
    ];
    for version in invalid {
        assert!(
            !is_semantic_version(version),
            "{version:?} should be invalid"
        );
    }
    // `MAX_LENGTH` is 256: 250 characters of prerelease is valid, 300 is not.
    assert!(is_semantic_version(&format!("1.2.3-{}", "a".repeat(250))));
    assert!(!is_semantic_version(&format!("1.2.3-{}", "a".repeat(300))));
}

