const RUNTIME: &str = "0.1.7-alpha.1";

/// The identity every case in the upstream suite starts from.
fn identity() -> Value {
    json!({ "name": "@example/plugin", "version": "2.0.0" })
}

/// `evaluatePluginCompatibility` over a peer map, with `node-semver`'s ranges.
fn check(manifest: &Value) -> Result<Option<boot_app_gap::PluginCompatibility>, String> {
    evaluate_plugin_compatibility(manifest, &BTreeMap::new(), RUNTIME, &satisfies)
}

/// `evaluatePluginCompatibility` over an `engines.dsh` range and an optional peer map.
fn engines(
    dsh: &Value,
    peers: &Value,
) -> Result<Option<boot_app_gap::PluginCompatibility>, String> {
    let mut manifest = identity();
    manifest["engines"] = json!({ "dsh": dsh });
    manifest["peerDependencies"] = peers.clone();
    check(&manifest)
}

#[test]
