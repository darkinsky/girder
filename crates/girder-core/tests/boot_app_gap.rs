//! Tests for `boot_app_gap`: `app-boot`'s launcher decisions and `config-editor`'s edit plan.
//!
//! # Where the expectations come from
//!
//! Four suites here are **differential against the real upstream code**, not against a reading of
//! it:
//!
//! - [`parse_env_matches_node_util_parse_env`] replays 96 `.env` documents — the ones the upstream
//!   suites write (project and Harness-home layers, proxies, endpoints, exports, comments, CRLF,
//!   quoting, escapes, continuations, degenerate lines) — comparing every key and value with
//!   `util.parseEnv` from Node 24.
//! - [`is_semantic_version_matches_node_semver`] replays 49 versions, plus two length cases, across
//!   `semver.valid` from
//!   `node-semver` 7.8.5, including the leading-zero, `MAX_SAFE_INTEGER`, `MAX_LENGTH`, and
//!   build-metadata rules.
//! - [`join_path_matches_node_path_resolve`] and [`file_url_matches_node_path_to_file_url`] replay
//!   the path spellings a patch file may contain, including the `~`/`#`/`%`/non-ASCII cases the
//!   `user-patches` suite turns into module URLs.
//! - [`resolve_config_path_matches_upstream`] is the upstream function transliterated, including its
//!   `cordis\.ya?ml` basename swap.
//!
//! The rest restate the upstream suites' own cases: `profile.spec.ts` for `dsh.profile.bundles`
//! reconciliation, retired bundles, template normalization, and the patch-file declaration;
//! `profile-plugins.spec.ts` for the inventory and the activation reconciliation;
//! `plugin-compatibility.spec.ts` for `engines.dsh`/peer resolution and the warning text;
//! `app-boot.spec.ts` for the startup audit's two diagnostics *verbatim*, including the inline
//! snapshot of the grouped failure report; and `config-editor`'s `edit` for the three document
//! outcomes.
//!
//! # Why the module is compiled by path
//!
//! The crate root's wiring is a separate change, so this compiles the exact source file rather than
//! a copy. Inside a `#[path]` module the `crate::` prefix would name *this* test crate, so every
//! reference to the library goes through `girder_core::{...}` — which is why the module itself
//! imports nothing from the crate root. `market_compat_gap` is compiled alongside for one reason:
//! it owns the `node-semver` range evaluator that [`evaluate_plugin_compatibility`] takes as a
//! parameter, and reusing it here proves the two modules' shared boundary rather than restating a
//! range evaluator.

