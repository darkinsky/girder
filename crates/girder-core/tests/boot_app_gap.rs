#[test]
fn join_path_matches_node_path_resolve() {
    let cases: &[(&str, &str, &str)] = &[
        ("/base", "cordis.yml", "/base/cordis.yml"),
        ("/base", "./cordis.yml", "/base/cordis.yml"),
        ("/base", "conf/app.yaml", "/base/conf/app.yaml"),
        ("/base", "../up.yml", "/up.yml"),
        ("/", "x.yml", "/x.yml"),
        ("/a/b/c", "../../d/e.yml", "/a/d/e.yml"),
        ("/base", "x/./y/../z.yml", "/base/x/z.yml"),
        ("/base", "a//b.yml", "/base/a/b.yml"),
        // An absolute name discards the base entirely.
        ("/base", "/abs/path.yml", "/abs/path.yml"),
        ("a", "..", "."),
        ("a/b", "../../..", ".."),
    ];
    for (base, name, expected) in cases {
        assert_eq!(
            &join_path(base, name),
            expected,
            "resolve({base:?}, {name:?})"
        );
    }
}

#[test]
fn file_url_matches_node_path_to_file_url() {
    let cases: &[(&str, &str)] = &[
        ("/tmp/a b.mjs", "file:///tmp/a%20b.mjs"),
        (
            "/tmp/absolute #100%.mjs",
            "file:///tmp/absolute%20%23100%25.mjs",
        ),
        ("/tmp/a+b&c,d;e=f.mjs", "file:///tmp/a+b&c,d;e=f.mjs"),
        ("/tmp/a(b)c!d.mjs", "file:///tmp/a(b)c!d.mjs"),
        // `~` is not unreserved to Node's URL codec, even though RFC 3986 says it is.
        ("/tmp/~x_y-z.mjs", "file:///tmp/%7Ex_y-z.mjs"),
        ("/tmp/a@b:c.mjs", "file:///tmp/a@b:c.mjs"),
        ("/tmp/plain.mjs", "file:///tmp/plain.mjs"),
        ("/tmp/a[1].mjs", "file:///tmp/a%5B1%5D.mjs"),
        ("/tmp/a^b|d.mjs", "file:///tmp/a%5Eb%7Cd.mjs"),
        ("/tmp/a'b.mjs", "file:///tmp/a'b.mjs"),
        ("//a", "file:///a"),
    ];
    for (path, expected) in cases {
        assert_eq!(&file_url(path), expected, "pathToFileURL({path:?})");
    }
}

#[test]
fn resolve_config_path_matches_upstream() {
    // No replay: the path is resolved and left alone.
    assert_eq!(
        resolve_config_path("./cordis.yml", None, "/base"),
        "/base/cordis.yml"
    );
    assert_eq!(
        resolve_config_path("conf/app.yaml", Some("record"), "/base"),
        "/base/conf/app.yaml"
    );
    // Replay swaps a cordis.yml/.yaml basename in place.
    assert_eq!(
        resolve_config_path("./cordis.yml", Some("replay"), "/base"),
        "/base/cordis.snapshot.yml"
    );
    assert_eq!(
        resolve_config_path("deep/cordis.yaml", Some("replay"), "/base"),
        "/base/deep/cordis.snapshot.yml"
    );
    // Replay leaves every other basename, and every other mode, alone.
    assert_eq!(
        resolve_config_path("custom.yml", Some("replay"), "/base"),
        "/base/custom.yml"
    );
    assert_eq!(
        resolve_config_path("a/cordis.yml", Some("REPLAY"), "/b/c"),
        "/b/c/a/cordis.yml"
    );
}

