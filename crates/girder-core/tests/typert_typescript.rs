//! Tests for the TypeScript client generator.
//!
//! The output is code a browser will run, so the assertions are about what a client needs: a schema
//! that rejects the wrong shape rather than only a type that describes it.

use girder_core::{
    Catalogue, Field, Method, ObjectSchema, Parameter, Schema, Variant, to_typescript,
};

fn catalogue() -> Catalogue {
    let mut catalogue = Catalogue::new(1);
    catalogue.define(ObjectSchema::new(
        "SessionSummary",
        vec![
            Field::required("id", Schema::String).with_docs("stable identity"),
            Field::required("turns", Schema::Int64),
            Field::optional("title", Schema::Optional(Box::new(Schema::String))),
        ],
    ));
    catalogue.add(
        Method::new("session", "page")
            .with_parameter(Parameter::required("limit", Schema::Int64))
            .with_parameter(Parameter::optional("after", Schema::String))
            .returning(Schema::Array(Box::new(Schema::Ref(
                "SessionSummary".to_owned(),
            )))),
    );
    catalogue
}

#[test]
fn the_output_names_itself_generated() {
    // A hand-edited generated file is lost on the next run; saying so in the file is the only place
    // an editor will see it.
    let output = to_typescript(&catalogue());

    assert!(output.starts_with("// Generated by girder typert"));
    assert!(output.contains("do not edit"));
}

#[test]
fn a_named_type_becomes_a_schema_and_a_type() {
    // Both: the schema validates at runtime, the type is what an editor uses.
    let output = to_typescript(&catalogue());

    assert!(output.contains("export const SessionSummarySchema = z.object("));
    assert!(output.contains("export type SessionSummary = z.infer<typeof SessionSummarySchema>"));
}

#[test]
fn an_integer_field_is_validated_as_an_integer() {
    // `number()` would accept 1.5 for a field the server reads as a count.
    let output = to_typescript(&catalogue());

    assert!(output.contains("turns: z.number().int()"), "{output}");
}

#[test]
fn an_optional_field_is_optional() {
    let output = to_typescript(&catalogue());

    assert!(
        output.contains("title: z.string().nullable().optional()"),
        "{output}"
    );
}

#[test]
fn a_documented_field_carries_its_description() {
    // The generated file is the client author's documentation.
    let output = to_typescript(&catalogue());

    assert!(output.contains(".describe('stable identity')"), "{output}");
}

#[test]
fn a_method_lists_its_input_and_output() {
    let output = to_typescript(&catalogue());

    assert!(output.contains("'session.page': {"), "{output}");
    assert!(output.contains("limit: z.number().int()"), "{output}");
    assert!(output.contains("after: z.string().optional()"), "{output}");
    assert!(
        output.contains("output: z.array(SessionSummarySchema)"),
        "{output}"
    );
}

#[test]
fn the_revision_is_exported() {
    // A client checks it against the server's to detect a stale build.
    let output = to_typescript(&catalogue());

    assert!(output.contains("export const revision = 1"), "{output}");
}

#[test]
fn a_union_branch_fixes_its_discriminator() {
    // A branch accepting any string would let through a value no variant owns.
    let mut catalogue = Catalogue::new(1);
    catalogue.define(ObjectSchema::new("Unused", vec![]));
    let union = Schema::OneOf(vec![
        Variant {
            tag: "completed".to_owned(),
            schema: Schema::Object(ObjectSchema::new(
                "Completed",
                vec![Field::required("turn", Schema::Int64)],
            )),
        },
        Variant {
            tag: "failed".to_owned(),
            schema: Schema::Object(ObjectSchema::new(
                "Failed",
                vec![Field::required("reason", Schema::String)],
            )),
        },
    ]);
    catalogue.add(Method::new("turn", "outcome").returning(union));

    let output = to_typescript(&catalogue);

    assert!(output.contains("kind: z.literal('completed')"), "{output}");
    assert!(output.contains("kind: z.literal('failed')"), "{output}");
}

#[test]
fn an_enum_value_list_becomes_a_union_of_literals() {
    let mut catalogue = Catalogue::new(1);
    catalogue.add(
        Method::new("goal", "set").with_parameter(Parameter::required(
            "phase",
            Schema::Enum(vec!["active".to_owned(), "paused".to_owned()]),
        )),
    );

    let output = to_typescript(&catalogue);

    assert!(
        output.contains("z.union([z.literal('active'), z.literal('paused')])"),
        "{output}"
    );
}

#[test]
fn a_map_becomes_a_record() {
    let mut catalogue = Catalogue::new(1);
    catalogue.add(Method::new("kv", "read").returning(Schema::Map(Box::new(Schema::Int64))));

    let output = to_typescript(&catalogue);

    assert!(
        output.contains("z.record(z.string(), z.number().int())"),
        "{output}"
    );
}

#[test]
fn an_opaque_value_becomes_unknown() {
    // `any()` would silently disable every check downstream of it.
    let mut catalogue = Catalogue::new(1);
    catalogue.add(Method::new("x", "y").with_parameter(Parameter::required("blob", Schema::Any)));

    let output = to_typescript(&catalogue);

    assert!(output.contains("blob: z.unknown()"), "{output}");
    assert!(
        !output.contains("z.any()"),
        "any() disables checking downstream"
    );
}

#[test]
fn a_property_that_is_not_an_identifier_is_quoted() {
    // A wire name can be anything; an unquoted non-identifier would be a syntax error.
    let mut catalogue = Catalogue::new(1);
    catalogue.add(
        Method::new("x", "y").with_parameter(Parameter::required("with-dash", Schema::String)),
    );

    let output = to_typescript(&catalogue);

    assert!(output.contains("'with-dash': z.string()"), "{output}");
}

#[test]
fn a_quote_in_a_description_cannot_break_the_literal() {
    // A doc comment is free text; an unescaped quote would end the string early.
    let mut catalogue = Catalogue::new(1);
    catalogue.define(ObjectSchema::new(
        "T",
        vec![Field::required("a", Schema::String).with_docs("it's documented")],
    ));

    let output = to_typescript(&catalogue);

    assert!(output.contains("it\\'s documented"), "{output}");
}

#[test]
fn a_method_with_no_parameters_renders_an_empty_input() {
    let mut catalogue = Catalogue::new(1);
    catalogue.add(Method::new("session", "list"));

    let output = to_typescript(&catalogue);

    assert!(output.contains("input: z.object({"), "{output}");
}

#[test]
fn several_methods_each_get_an_entry() {
    let mut catalogue = Catalogue::new(1);
    catalogue.add(Method::new("a", "one"));
    catalogue.add(Method::new("b", "two"));

    let output = to_typescript(&catalogue);

    assert!(output.contains("'a.one': {"), "{output}");
    assert!(output.contains("'b.two': {"), "{output}");
}

#[test]
fn comments_use_typescript_syntax() {
    // `///` is a Rust doc comment. In TypeScript it is a plain comment that no editor attaches to
    // the symbol, so the generated documentation would be invisible.
    let output = to_typescript(&catalogue());

    assert!(
        !output.contains("///"),
        "TypeScript has no `///` doc comments:\n{output}"
    );
    assert!(output.contains("/**"), "{output}");
}

#[test]
fn the_output_is_roughly_balanced() {
    // A missing brace produces a file the client cannot parse, which is worse than a wrong schema
    // because nothing runs at all.
    let output = to_typescript(&catalogue());
    let opens = output.chars().filter(|c| *c == '{').count();
    let closes = output.chars().filter(|c| *c == '}').count();

    assert_eq!(opens, closes, "unbalanced braces:\n{output}");
}

#[test]
fn an_empty_catalogue_still_produces_a_module() {
    // A build with no Remote methods must not emit a broken file.
    let output = to_typescript(&Catalogue::new(7));

    assert!(output.contains("export const methods = {"));
    assert!(output.contains("export const revision = 7"));
    assert_eq!(
        output.chars().filter(|c| *c == '{').count(),
        output.chars().filter(|c| *c == '}').count()
    );
}
